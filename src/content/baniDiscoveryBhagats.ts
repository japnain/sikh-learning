import type { BaniDiscoveryEntries, BaniDiscoveryEntry } from './baniDiscoveryTypes'

// Checked against every selected reading's headings and opening/closing text
// in BaniDB on 31 October 2026. These are selections, not entire raag sections.
function selection(id: number, name: string, summary: string, detail: string, ...angs: number[]): BaniDiscoveryEntry {
  return {
    name, summary, detail,
    references: [
      ...angs.map(ang => ({ label: `Guru Granth Sahib · Ang ${ang}`, url: `https://www.srigranth.org/servlet/gurbani.gurbani?Action=Page&Param=${ang}&g=1&h=0&r=0&t=1&p=0` })),
      { label: 'Selected reading · BaniDB', url: `https://api.banidb.com/v2/banis/${id}` },
    ],
  }
}

