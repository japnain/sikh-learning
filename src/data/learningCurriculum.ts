export const LEARN_MODULE_BY_ID = Object.fromEntries(
  LEARN_MODULES.map(module => [module.id, module])
) as Record<string, LearnModule>

export const PROGRAM_MODULES = Object.fromEntries(
  LEARN_PROGRAMS.map(program => [
    program.id,
    LEARN_MODULES.filter(module => module.programId === program.id),
  ])
) as Record<LearnProgramId, LearnModule[]>

export function getDefaultProgramForLevel(level: LearningLevel): LearnProgramId {
  if (level === 'beginner') return 'start-reading'
  if (level === 'familiar') return 'build-fluency'
  return 'understand-gurbani'
}

export function getLearningSkillKind(module: LearnModule): LearningSkillKind {
  if (module.type === 'symbol') return 'symbol'
  if (module.type === 'sound') return 'sound'
  if (module.type === 'decode') return 'pattern'
  if (module.type === 'guided') return 'guided-reading'
  return 'comprehension'
}
